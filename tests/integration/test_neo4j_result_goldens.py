"""Result goldens from Neo4j (P-4c S1, docs/design/EXPLICIT_SCOPE.md §6).

Each `tests/corpus/expected/<schema>/<name>.json` holds the rows Neo4j 5.26
returns for a corpus query on the same logical graph (generated by
`scripts/oracle/run_corpus.py --write-expected`). This test runs the query on
ClickGraph and compares rows with `scripts/oracle/compare.py`, so no Neo4j is
needed here.

`tests/corpus/expected/scorecard.json` records today's verdict per query:
  * MATCH / LIMIT_COUNT_ONLY / LIMIT_TIES -> must stay correct;
  * MISMATCH / CG_ERROR -> known wrong (strict xfail): when a fix makes one
    correct, this test fails until the scorecard is regenerated, so every
    flip is recorded;
  * INCOMPARABLE / NEO_ERROR / BOTH_ERROR -> not scored.

Each corpus schema is resolved as the corpus sweep resolves it
(`tests/corpus/schema_map.json`) and registered under a private name
(`oracle__<schema>`), so schema re-registrations by other tests cannot change
which tables these queries read.
"""
import json
import os
import sys

import pytest
import requests

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "scripts", "oracle"))
import compare  # noqa: E402
import graph_loader  # noqa: E402

CLICKGRAPH_URL = os.getenv("CLICKGRAPH_URL", "http://localhost:7475")
EXPECTED_DIR = os.path.join(REPO, "tests", "corpus", "expected")
GOOD = {"MATCH", "LIMIT_COUNT_ONLY", "LIMIT_TIES"}
KNOWN_WRONG = {"MISMATCH", "CG_ERROR"}


def _goldens():
    scorecard = json.load(open(os.path.join(EXPECTED_DIR, "scorecard.json")))
    out = []
    for key, verdict in sorted(scorecard.items()):
        if verdict not in GOOD | KNOWN_WRONG:
            continue
        marks = []
        if verdict in KNOWN_WRONG:
            marks.append(pytest.mark.xfail(strict=True, reason=f"known wrong today ({verdict})"))
        out.append(pytest.param(key, id=key, marks=marks))
    return out


@pytest.fixture(scope="module")
def oracle_schemas():
    """Register every golden schema as `oracle__<schema>`; returns the map."""
    names = {}
    for schema in sorted(os.listdir(EXPECTED_DIR)):
        if not os.path.isdir(os.path.join(EXPECTED_DIR, schema)):
            continue
        private = f"oracle__{schema}"
        content = graph_loader.registration_yaml(schema, private, repo=REPO)
        r = requests.post(
            f"{CLICKGRAPH_URL}/schemas/load",
            json={"schema_name": private, "config_content": content},
            timeout=60,
        )
        r.raise_for_status()
        names[schema] = private
    return names


def _run(schema_name, cypher):
    r = requests.post(
        f"{CLICKGRAPH_URL}/query",
        json={"query": cypher, "schema_name": schema_name},
        timeout=120,
    )
    if r.status_code != 200:
        return None, f"HTTP {r.status_code}: {r.text[:300]}"
    return r.json().get("results", []), None


@pytest.mark.parametrize("key", _goldens())
def test_rows_match_neo4j(key, oracle_schemas):
    schema, name = key.split("/", 1)
    expected = json.load(open(os.path.join(EXPECTED_DIR, schema, name + ".json")))
    cypher = expected["cypher"]
    rows, err = _run(oracle_schemas[schema], cypher)
    assert err is None, f"ClickGraph error (Neo4j answers): {err}\n{cypher}"
    verdict, detail = compare.compare_expected(cypher, expected, rows)
    if verdict == "MISMATCH" and "same count" in detail and "full" in expected:
        full = compare.without_trailing_limit(cypher)
        full_rows, full_err = _run(oracle_schemas[schema], full)
        if full_err is None and compare.compare_expected(full, expected["full"], full_rows)[0] == "MATCH":
            verdict = "LIMIT_TIES"
    assert verdict in GOOD, f"{verdict}: {detail}\n{cypher}"
