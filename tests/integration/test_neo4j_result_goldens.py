"""Result goldens from Neo4j (P-4c S1, docs/design/EXPLICIT_SCOPE.md §6).

Each `tests/corpus/expected/<schema>/<name>.json` holds the rows Neo4j 5.26
returns for a corpus query on the same logical graph (generated by
`scripts/oracle/run_corpus.py --write-expected`). This test runs the query on
ClickGraph and compares rows with `scripts/oracle/compare.py`, so no Neo4j is
needed here.

`tests/corpus/expected/scorecard.json` records each query's verdict today:
  * MATCH -> must stay correct;
  * MISMATCH / CG_ERROR (known wrong) -> must keep its recorded wrong outcome
    (signature). If a fix makes it correct, the test fails until the scorecard
    is regenerated, so every flip is recorded. If it drifts to a DIFFERENT
    wrong answer, the test fails too. Otherwise it is reported as xfail.

The ClickHouse fixture data must be the data the goldens were generated
from: each schema's `_graph.json` (node and relationship counts) is checked
first.

Each corpus schema is resolved as the corpus sweep resolves it
(`tests/corpus/schema_map.json`) and registered under a private name
(`oracle__<schema>`), so schema re-registrations by other tests cannot change
which tables these queries read.
"""
import json
import os
import sys

import pytest
import requests

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "scripts", "oracle"))
import compare  # noqa: E402
import graph_loader  # noqa: E402

CLICKGRAPH_URL = os.getenv("CLICKGRAPH_URL", "http://localhost:7475")
CLICKHOUSE_URL = os.getenv("CLICKHOUSE_URL", "http://localhost:8123")
CLICKHOUSE_USER = os.getenv("CLICKHOUSE_USER", "test_user")
CLICKHOUSE_PASSWORD = os.getenv("CLICKHOUSE_PASSWORD", "test_pass")
EXPECTED_DIR = os.path.join(REPO, "tests", "corpus", "expected")
KNOWN_WRONG = ("MISMATCH", "CG_ERROR")


def _scorecard():
    return json.load(open(os.path.join(EXPECTED_DIR, "scorecard.json")))


@pytest.fixture(scope="module")
def oracle_schemas():
    """Check each golden schema's data fingerprint, then register it as
    `oracle__<schema>`; returns the corpus-schema -> private-name map."""
    ch = lambda sql: graph_loader.ch_rows(  # noqa: E731
        CLICKHOUSE_URL.rstrip("/") + "/", CLICKHOUSE_USER, CLICKHOUSE_PASSWORD, sql
    )
    names = {}
    for schema in sorted(os.listdir(EXPECTED_DIR)):
        d = os.path.join(EXPECTED_DIR, schema)
        if not os.path.isdir(d):
            continue
        gs = graph_loader.corpus_schema_doc(schema, repo=REPO)["graph_schema"]
        _nodes, _rels, report = graph_loader.build_graph(gs, ch)
        stored = json.load(open(os.path.join(d, "_graph.json")))
        assert report == stored, (
            f"{schema}: the ClickHouse fixture data differs from the data the goldens "
            f"were generated from ({report} vs {stored}); regenerate with run_corpus.py"
        )
        private = f"oracle__{schema}"
        r = requests.post(
            f"{CLICKGRAPH_URL}/schemas/load",
            json={"schema_name": private, "config_content": graph_loader.registration_yaml(schema, private, repo=REPO)},
            timeout=60,
        )
        r.raise_for_status()
        names[schema] = private
    return names


def _run(schema_name, cypher):
    r = requests.post(
        f"{CLICKGRAPH_URL}/query",
        json={"query": cypher, "schema_name": schema_name},
        timeout=120,
    )
    if r.status_code != 200:
        return None, f"HTTP {r.status_code}: {r.text[:300]}"
    return r.json().get("results", []), None


@pytest.mark.parametrize("key", sorted(_scorecard()))
def test_rows_match_neo4j(key, oracle_schemas):
    recorded = _scorecard()[key]
    schema, name = key.split("/", 1)
    expected = json.load(open(os.path.join(EXPECTED_DIR, schema, name + ".json")))
    cypher = expected["cypher"]
    rows, err = _run(oracle_schemas[schema], cypher)
    if err is not None:
        verdict, detail = "CG_ERROR", err
    else:
        verdict, detail = compare.compare_expected(cypher, expected, rows)
    if recorded["verdict"] == "MATCH":
        assert verdict == "MATCH", f"{verdict}: {detail}\n{cypher}"
        return
    assert verdict != "MATCH", (
        f"known-wrong entry is now CORRECT: regenerate the scorecard "
        f"(scripts/oracle/run_corpus.py --write-expected)\n{cypher}"
    )
    signature = compare.signature(verdict, detail, rows)
    assert (verdict, signature) == (recorded["verdict"], recorded["signature"]), (
        f"known-wrong entry changed its wrong outcome ({recorded['verdict']} -> {verdict}: "
        f"{detail}); check the change and regenerate the scorecard\n{cypher}"
    )
    pytest.xfail(f"known wrong ({verdict}); triage.json")
